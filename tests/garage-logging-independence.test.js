'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const src = fs.readFileSync(path.join(__dirname, '..', 'lib/garage/GarageSafetyEngine.js'), 'utf8');
const device = fs.readFileSync(path.join(__dirname, '..', 'drivers/mower/device.js'), 'utf8');
const app = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const api = fs.readFileSync(path.join(__dirname, '..', 'api.js'), 'utf8');
const recovery = fs.readFileSync(path.join(__dirname, '..', 'lib/garage/CoreExternalStartRecovery.js'), 'utf8');
const compose = require('../drivers/mower/driver.compose.json');
const settings = compose.settings.find(g => g.label?.en === 'Garage Safety').children;
const names = new Set(settings.map(s => s.id));
assert.ok(names.has('garage_logging_enabled') && names.has('garage_debug_verbose'));
assert.ok(!names.has('garage_external_core_intercept_enabled'), 'do not reintroduce extra arming switch');
const timeline = src.slice(src.indexOf('  _timeline(message,'), src.indexOf('    const clean =', src.indexOf('  _timeline(message,')));
assert.ok(!timeline.includes("getSetting('garage_mode_enabled')"), 'timeline logging independent of garage mode');
assert.ok(timeline.includes("getSetting('garage_debug_verbose')"), 'debug alone enables timeline');
const log = src.slice(src.indexOf('  log(...args) {'), src.indexOf('  error(...args) {', src.indexOf('  log(...args) {')));
assert.ok(log.includes("getSetting('garage_debug_verbose')"), 'debug alone enables garage log forwarding');
assert.ok(log.includes('this.device.log('), 'logs still forward through device');
assert.ok(device.includes('this.homey.app._pushLog('), 'device streams logs to app');
assert.ok(app.includes('getLogs(since = 0)') && api.includes("deviceId === '__logs__'"), 'Windows API log polling remains');
assert.ok(recovery.includes('return !!this.garage?.enabled?.()'), 'Garage Mode arms recovery');
console.log('PASS: logging remains independent from garage mode and Windows log API intact');
